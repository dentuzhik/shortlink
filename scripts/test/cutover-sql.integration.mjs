import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { readFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { test } from "node:test";
import { setTimeout as delay } from "node:timers/promises";
import {
  admitTargetSql,
  fenceSql,
  hash,
  prepareTargetSql,
  sequenceSql,
  sequenceTarget,
  stopStreamSql,
} from "../lib/cutover.mjs";
import { sequencesSql } from "../lib/cutover-live.mjs";
import { run } from "../lib/db-lab-connectivity.mjs";

const require = createRequire(
  new URL("../../apps/redirect-service/package.json", import.meta.url),
);
const { Client } = require("pg");
const id = randomBytes(16).toString("hex");
const docker = (args) =>
  run(
    "docker",
    ["--context", process.env.CI ? "default" : "colima", ...args],
    undefined,
    30000,
  );
const identity = `SELECT json_build_object('systemId',(SELECT system_identifier::text FROM pg_control_system()),'databaseOid',(SELECT oid::text FROM pg_database WHERE datname=current_database()),'linksOid','links'::regclass::oid::text,'historyOid','drizzle.__drizzle_migrations'::regclass::oid::text) AS value;`;
const schema = `CREATE TABLE links(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,code text UNIQUE NOT NULL,target_url text NOT NULL,created_at timestamptz NOT NULL DEFAULT now());CREATE SCHEMA drizzle;CREATE TABLE drizzle.__drizzle_migrations(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,hash text,created_at bigint);`;
const value = async (client, sql) =>
  (await client.query(sql)).rows[0].json_build_object;
const jsonResult = (result) =>
  (Array.isArray(result) ? result : [result])
    .flatMap((x) => x.rows ?? [])
    .find((x) => x.json_build_object)?.json_build_object;
async function wait(work) {
  const end = Date.now() + 15000;
  while (!(await work())) {
    assert.ok(Date.now() < end, "Fixture database did not catch up");
    await delay(50);
  }
}

test("guarded cutover SQL on two disposable Postgres instances", {
  timeout: 90000,
}, async (t) => {
  const containers = [];
  const clients = [];
  t.after(async () => {
    for (const client of clients) await client.end().catch(() => {});
    for (const name of containers.reverse()) {
      const [object] = JSON.parse(await docker(["inspect", name]));
      assert.equal(object.Config.Labels["shortlink.cutover-fixture"], id);
      await docker(["rm", "--force", "--volumes", name]);
    }
  });
  const image = JSON.parse(
    await readFile("deploy/migration/rehearsal.json", "utf8"),
  ).publisherImage;
  const fixtures = [];
  for (const side of ["source", "target"]) {
    const name = `cutover-sql-${id.slice(0, 12)}-${side}`;
    await docker([
      "run",
      "--detach",
      "--name",
      name,
      "--label",
      `shortlink.cutover-fixture=${id}`,
      "--memory=128m",
      "--shm-size=32m",
      "--publish",
      "127.0.0.1::5432",
      "--env",
      "POSTGRES_HOST_AUTH_METHOD=trust",
      "--env",
      "POSTGRES_USER=fixture_admin",
      "--env",
      "POSTGRES_DB=shortener",
      image,
      "-c",
      "shared_buffers=16MB",
      "-c",
      "max_connections=20",
      "-c",
      "wal_level=logical",
      "-c",
      "max_wal_size=128MB",
    ]);
    containers.push(name);
    const [object] = JSON.parse(await docker(["inspect", name]));
    const port = Number(object.NetworkSettings.Ports["5432/tcp"][0].HostPort);
    let client;
    await wait(async () => {
      const candidate = new Client({
        host: "127.0.0.1",
        port,
        user: "fixture_admin",
        database: "shortener",
        connectionTimeoutMillis: 1000,
      });
      try {
        await candidate.connect();
        client = candidate;
        return true;
      } catch {
        await candidate.end().catch(() => {});
        return false;
      }
    });
    clients.push(client);
    await client.query(schema);
    await client.query(
      await readFile("deploy/migration/application-runtime-role.sql", "utf8"),
    );
    await client.query("ALTER ROLE shortlink_app LOGIN");
    fixtures.push({
      client,
      port,
      address: object.NetworkSettings.Networks.bridge.IPAddress,
    });
  }
  const [source, target] = fixtures;
  await source.client.query(
    "INSERT INTO links(code,target_url) VALUES('seed0001','https://example.test/seed');CREATE PUBLICATION shortlink_migration FOR TABLE links,drizzle.__drizzle_migrations;",
  );
  await target.client.query(
    `CREATE SUBSCRIPTION shortlink_migration_sub CONNECTION 'host=${source.address} dbname=shortener user=fixture_admin' PUBLICATION shortlink_migration;`,
  );
  await wait(
    async () =>
      (await target.client.query("SELECT count(*)::int AS n FROM links"))
        .rows[0].n === 1,
  );
  const body = {
    format: "shortlink-cutover-v1",
    id,
    marker: {
      code: "marker01",
      targetUrl: `https://example.invalid/cutover/${id}`,
    },
    canaryUrl: `https://example.invalid/cutover-canary/${id}`,
    initialControl: {
      revision: 4,
      creationMode: "accept",
      activeDatabase: "source",
      prepareDatabase: "ha",
    },
    binding: {
      pods: [{}, {}],
      source: (await source.client.query(identity)).rows[0].value,
      ha: (await target.client.query(identity)).rows[0].value,
    },
  };
  const plan = { ...body, planHash: hash(body) };
  const runtime = new Client({
    host: "127.0.0.1",
    port: source.port,
    user: "shortlink_app",
    database: "shortener",
  });
  await runtime.connect();
  clients.push(runtime);
  const oldPid = (await runtime.query("SELECT pg_backend_pid() AS pid")).rows[0]
    .pid;
  await runtime.query(
    "INSERT INTO links(code,target_url) VALUES('before01','https://example.test/before')",
  );
  await t.test("a valid plan cannot fence the other database", async () => {
    await assert.rejects(
      target.client.query(fenceSql(plan)),
      (e) => e.code === "P0001",
    );
    await target.client.query("ROLLBACK");
    assert.equal(
      (
        await target.client.query(
          "SELECT has_table_privilege('shortlink_app','links','INSERT') AS allowed",
        )
      ).rows[0].allowed,
      true,
    );
  });
  let marker;
  await t.test(
    "an inherited PUBLIC write grant prevents fencing and rolls back the marker transaction",
    async () => {
      await source.client.query("GRANT INSERT ON links TO PUBLIC");
      await assert.rejects(
        source.client.query(fenceSql(plan)),
        (e) => e.code === "P0001",
      );
      await source.client.query("ROLLBACK");
      assert.equal(
        (
          await source.client.query(
            "SELECT count(*)::int AS n FROM links WHERE code=$1",
            [plan.marker.code],
          )
        ).rows[0].n,
        0,
      );
      await source.client.query("REVOKE INSERT ON links FROM PUBLIC");
    },
  );
  await t.test(
    "fencing revokes INSERT on the same open session while retaining reads",
    async () => {
      marker = jsonResult(await source.client.query(fenceSql(plan)));
      await assert.rejects(
        runtime.query(
          "INSERT INTO links(code,target_url) VALUES('denied01','https://example.test/denied')",
        ),
        (e) => e.code === "42501",
      );
      assert.equal(
        (await runtime.query("SELECT pg_backend_pid() AS pid")).rows[0].pid,
        oldPid,
      );
      assert.ok(
        (await runtime.query("SELECT count(*)::int AS n FROM links")).rows[0]
          .n > 0,
      );
    },
  );
  await t.test(
    "replaying a lost fence acknowledgement emits a committed marker transaction that reaches the new WAL boundary",
    async () => {
      marker = jsonResult(await source.client.query(fenceSql(plan)));
      await wait(async () => {
        const r = await target.client.query(
          "SELECT EXISTS(SELECT 1 FROM links WHERE code=$1 AND target_url=$2) AND pg_replication_origin_progress('pg_'||(SELECT oid::text FROM pg_subscription WHERE subname='shortlink_migration_sub'),true)>=$3::pg_lsn AS applied",
          [plan.marker.code, plan.marker.targetUrl, marker.lsn],
        );
        return r.rows[0].applied;
      });
      assert.equal(
        (
          await source.client.query(
            "SELECT count(*)::int AS n FROM links WHERE code=$1",
            [plan.marker.code],
          )
        ).rows[0].n,
        1,
      );
    },
  );
  const sourceSeq = await value(source.client, sequencesSql);
  let prepared;
  await t.test(
    "sequence preparation requires the pinned administrator control row",
    async () => {
      await assert.rejects(
        target.client.query(
          sequenceSql(plan, "public.links_id_seq", {
            last_value: "1",
            is_called: false,
          }),
        ),
        (e) => e.code === "42P01",
      );
      await target.client.query("ROLLBACK");
      await target.client.query(prepareTargetSql(plan));
      const current = await value(target.client, sequencesSql);
      prepared = {};
      for (const [name, seq] of Object.entries(current)) {
        prepared[name] = sequenceTarget(sourceSeq[name], seq);
        await target.client.query(sequenceSql(plan, name, prepared[name]));
      }
      assert.ok(
        BigInt(prepared["public.links_id_seq"].last_value) >
          BigInt(marker.marker.id),
      );
    },
  );
  await t.test(
    "an old sequence parameter cannot rewind an already prepared allocation",
    async () => {
      await target.client.query(
        sequenceSql(plan, "public.links_id_seq", {
          last_value: "1",
          is_called: false,
        }),
      );
      const current = await value(target.client, sequencesSql);
      assert.equal(
        current["public.links_id_seq"].last_value,
        prepared["public.links_id_seq"].last_value,
      );
    },
  );
  await t.test(
    "stopping replication seals the sequence phase and retains its publisher slot",
    async () => {
      await target.client.query(stopStreamSql(plan));
      await wait(
        async () =>
          (
            await target.client.query(
              "SELECT count(*)::int AS n FROM pg_stat_subscription WHERE pid IS NOT NULL",
            )
          ).rows[0].n === 0,
      );
      assert.equal(
        (
          await source.client.query(
            "SELECT count(*)::int AS n FROM pg_replication_slots WHERE slot_name='shortlink_migration_sub'",
          )
        ).rows[0].n,
        1,
      );
      await assert.rejects(
        target.client.query(
          sequenceSql(plan, "public.links_id_seq", {
            last_value: "1",
            is_called: false,
          }),
        ),
        (e) => e.code === "P0001",
      );
      await target.client.query("ROLLBACK");
    },
  );
  await t.test(
    "HA admission is idempotent and delayed sequence/stop commands cannot affect the new writer",
    async () => {
      await target.client.query(admitTargetSql(plan));
      await target.client.query(admitTargetSql(plan));
      const app = new Client({
        host: "127.0.0.1",
        port: target.port,
        user: "shortlink_app",
        database: "shortener",
      });
      await app.connect();
      clients.push(app);
      const created = (
        await app.query(
          "INSERT INTO links(code,target_url) VALUES('after001',$1) RETURNING id::text",
          [plan.canaryUrl],
        )
      ).rows[0];
      assert.ok(
        BigInt(created.id) >=
          BigInt(prepared["public.links_id_seq"].last_value),
      );
      const before = await value(target.client, sequencesSql);
      for (const sql of [
        sequenceSql(plan, "public.links_id_seq", {
          last_value: "1",
          is_called: false,
        }),
        stopStreamSql(plan),
        prepareTargetSql(plan),
      ]) {
        await assert.rejects(
          target.client.query(sql),
          (e) => e.code === "P0001",
        );
        await target.client.query("ROLLBACK");
      }
      assert.deepEqual(await value(target.client, sequencesSql), before);
      await assert.rejects(
        app.query("SELECT * FROM shortlink_cutover.control"),
        (e) => e.code === "42501",
      );
      assert.equal(
        (
          await source.client.query(
            "SELECT count(*)::int AS n FROM links WHERE target_url=$1",
            [plan.canaryUrl],
          )
        ).rows[0].n,
        0,
      );
    },
  );
});
